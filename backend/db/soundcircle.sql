CREATE DATABASE IF NOT EXISTS SoundCircle CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

USE SoundCircle;

CREATE TABLE IF NOT EXISTS Caracteristica (
  id int NOT NULL AUTO_INCREMENT,
  nome varchar(100) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY nome (nome)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS Instrumento (
  id int NOT NULL AUTO_INCREMENT,
  nome varchar(100) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY nome (nome)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS User (
  id int NOT NULL AUTO_INCREMENT,
  nome varchar(100) NOT NULL,
  email varchar(150) NOT NULL,
  password_hash varchar(255) NOT NULL,
  tipo enum('solo','banda') NOT NULL,
  descricao text,
  foto_url varchar(255) DEFAULT NULL,
  data_nascimento date DEFAULT NULL,
  localizacao varchar(250) DEFAULT NULL,
  sexo varchar(50) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS User_inst (
  user_id int NOT NULL,
  instrumento_id int NOT NULL,
  nivel enum('iniciante','intermedio','avancado','profissional') DEFAULT NULL,
  anos_experiencia int unsigned DEFAULT NULL,
  PRIMARY KEY (user_id, instrumento_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS UserCar (
  user_id int NOT NULL,
  caracteristica_id int NOT NULL,
  PRIMARY KEY (user_id, caracteristica_id),
  KEY fk_usercar_caract (caracteristica_id),
  CONSTRAINT fk_usercar_caract FOREIGN KEY (caracteristica_id) REFERENCES Caracteristica (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_usercar_user FOREIGN KEY (user_id) REFERENCES User (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS mensagens (
  id int NOT NULL AUTO_INCREMENT,
  remetente_id int NOT NULL,
  destinatario_id int NOT NULL,
  conteudo text,
  data_envio timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  media_path varchar(255) DEFAULT NULL,
  media_tipo enum('imagem','video') DEFAULT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

